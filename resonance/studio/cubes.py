import json
from pathlib import Path

DATA_PATH = Path(__file__).parent / "data" / "parallel-cubes.json"


def _factorize(n):
    """Prime factorization {prime: exponent} by trial division. Pure.

    MECHANISM: the same naive road as pontifex/cubes.py — the cubes
    are under a million, so nothing cleverer is honest.
    """
    factors = {}
    d = 2
    while d * d <= n:
        while n % d == 0:
            factors[d] = factors.get(d, 0) + 1
            n //= d
        d += 1
    if n > 1:
        factors[n] = factors.get(n, 0) + 1
    return factors


def load_record():
    """The shared record, parsed from data/parallel-cubes.json.

    MECHANISM: a plain JSON read at call time (never cached into a
    literal), so the file on disk is the record — edit the file and
    every reader sees the edit, and cubes_checks() judges it.
    """
    return json.loads(DATA_PATH.read_text(encoding="utf-8"))


def parallel_summary():
    """The compact parallel, as a run summary cites it.

    MECHANISM: the two cube rows reduced to their sworn figures
    (base, cube, factorization, threefold) plus the declared
    equation's two figures — the summary a scene prints is measured
    from the record, and the record is checked against arithmetic.
    """
    record = load_record()
    out = {}
    for key, row in record["cubes"].items():
        out[key] = {
            "base": row["base"],
            "cube": row["cube"],
            "factorization": row["factorization"],
            "threefold": row["threefold"],
        }
    de = record["declared_equation"]
    out["declared_equation"] = {
        "inscription": de["inscription"],
        "by_multiplication": de["by_multiplication"],
        "by_threefold_sum": de["by_threefold_sum"],
    }
    return out


def cubes_checks():
    """Self-checks for the studio's reading of the record.

    MECHANISM: every figure in the JSON is re-derived from the base
    the JSON itself declares — square, cube by multiplication,
    factorization by trial division on the cube, threefold — and
    the declared equation's two figures are asserted apart, so
    neither can swallow the other. Returns [(name, passed, got)]
    on the pontifex pattern.
    """
    record = load_record()
    checks = []
    for key in ("77", "93"):
        row = record["cubes"][key]
        base = row["base"]
        cube = base ** 3
        facts = _factorize(cube)
        ok = (row["square"] == base ** 2 and row["cube"] == cube
              and row["threefold"] == 3 * cube
              and {str(p): e for p, e in facts.items()}
              == row["factorization"])
        checks.append((f"cube {key}: record == arithmetic re-derived "
                       f"from base {base}", ok,
                       (row["cube"], row["factorization"])))
    de = record["declared_equation"]
    checks.append(("declared equation: 29,791 by multiplication, "
                   "93 by the threefold sum — both figures stand",
                   de["by_multiplication"] == 29791
                   and de["by_threefold_sum"] == 93
                   and de["inscription"] == "31^3 = 93",
                   (de["by_multiplication"], de["by_threefold_sum"])))
    seats = record["greek_seats"]
    checks.append(("Greek seats as recorded from PONTIFEX: "
                   "KY 420, thelema 93",
                   seats["KY"]["value"] == 420
                   and seats["thelema"]["value"] == 93,
                   (seats["KY"]["value"], seats["thelema"]["value"])))
    return checks


